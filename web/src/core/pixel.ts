// 10×10 pixel icons on the same grid as the hero tiles. '#' = filled.

/** One filled 1×1 square per '#', as an SVG path for a 10×10 viewBox. */
export function toPath(rows: readonly string[]): string {
  let d = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === '#') d += 'M' + x + ' ' + y + 'h1v1h-1z';
  });
  return d;
}

