export type IconName = keyof typeof ICONS;

export const iconPath = (key: IconName): string => '<path d="' + toPath(ICONS[key]) + '" fill="currentColor"></path>';

const isIcon = (key: string | null): key is IconName => key !== null && key in ICONS;

/** Fills every <svg data-icon="…"> in the markup with its icon. */
export function paintIcons(root: ParentNode = document): void {
  root.querySelectorAll('svg[data-icon]').forEach((el) => {
    const key = el.getAttribute('data-icon');
    if (isIcon(key)) el.innerHTML = iconPath(key);
  });
}
